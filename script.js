function markCompleted(index) {
  state.completed.add(index);
  localStorage.setItem("book-completed", JSON.stringify([...state.completed]));
  renderChapters();
}

function updateProgress() {
  const count = state.completed.size;
  $("#heroProgress").style.width = `${(count / chapters.length) * 100}%`;
  $("#heroProgressText").textContent = `${count} de ${chapters.length} capítulos`;
}

function getChapterSpeech(chapter = chapters[state.currentChapter]) {
  return `${chapter.title}. ${chapter.opening}. ${chapter.narrative.join(" ")} Lo que dije: ${chapter.said}. Lo que sentí: ${chapter.felt}. Lo que necesitaba decir: ${chapter.needed}.`;
}

function speak(text, button) {
  if (!("speechSynthesis" in window)) {
    showToast("Este navegador no ofrece lectura por voz.");
    return;
  }
  stopSpeech();
  const utterance = new SpeechSynthesisUtterance(text);
  utterance.lang = "es-PE";
  utterance.rate = 0.94;
  utterance.pitch = 1;
  const voices = speechSynthesis.getVoices();
  const preferred = voices.find(voice => voice.lang.toLowerCase() === "es-pe") || voices.find(voice => voice.lang.toLowerCase().startsWith("es"));
  if (preferred) utterance.voice = preferred;
  utterance.onstart = () => {
    state.speech = utterance;
    if (button) button.textContent = "■ Detener";
  };
  utterance.onend = utterance.onerror = () => {
    state.speech = null;
    if (button) button.textContent = button.id === "readerSpeak" ? "▶ Escuchar" : button.dataset.original || button.textContent;
  };
  speechSynthesis.speak(utterance);
}

function stopSpeech() {
  if ("speechSynthesis" in window) speechSynthesis.cancel();
  state.speech = null;
  const readerSpeak = $("#readerSpeak");
  if (readerSpeak) readerSpeak.textContent = "▶ Escuchar";
}

function showToast(message) {
  toast.textContent = message;
  toast.classList.add("visible");
  clearTimeout(showToast.timer);
  showToast.timer = setTimeout(() => toast.classList.remove("visible"), 3200);
}

function playBell() {
  try {
    const AudioCtx = window.AudioContext || window.webkitAudioContext;
    if (!AudioCtx) return;
    const context = new AudioCtx();
    const now = context.currentTime;
    [659.25, 783.99].forEach((frequency, i) => {
      const oscillator = context.createOscillator();
      const gain = context.createGain();
      oscillator.type = "sine";
      oscillator.frequency.value = frequency;
      gain.gain.setValueAtTime(0.0001, now);
      gain.gain.exponentialRampToValueAtTime(0.16, now + .015 + i * .06);
      gain.gain.exponentialRampToValueAtTime(0.0001, now + 1.25 + i * .1);
      oscillator.connect(gain).connect(context.destination);
      oscillator.start(now + i * .08);
      oscillator.stop(now + 1.5);
    });
  } catch (_) {
    // Ambient sound is optional.
  }
}

function emojiForEmotion(emotion) {
  return ({ tranquilo: "😌", curioso: "🤔", nervioso: "😟", alegre: "😊", incómodo: "😣" })[emotion] || "";
}

function restoreEmotionMap() {
  Object.entries(state.emotions).forEach(([place, emotion]) => {
    const button = $(`[data-place="${place}"]`);
    if (button) button.dataset.savedEmotion = emojiForEmotion(emotion);
  });
}

function setupActivities() {
  const picker = $("#emotionPicker");
  $$("#schoolMap button").forEach(button => {
    button.addEventListener("click", () => {
      $$("#schoolMap button").forEach(item => item.classList.remove("selected"));
      button.classList.add("selected");
      state.selectedPlace = button.dataset.place;
      $("#emotionQuestion").textContent = `¿Cómo te hace sentir ${state.selectedPlace.toLowerCase()}?`;
      picker.hidden = false;
    });
  });
  $$("#emotionPicker button").forEach(button => {
    button.addEventListener("click", () => {
      if (!state.selectedPlace) return;
      const emotion = button.dataset.emotion;
      state.emotions[state.selectedPlace] = emotion;
      localStorage.setItem("book-emotions", JSON.stringify(state.emotions));
      const placeButton = $(`[data-place="${state.selectedPlace}"]`);
      placeButton.dataset.savedEmotion = emojiForEmotion(emotion);
      showToast(`${state.selectedPlace}: ${emotion}. Puedes cambiarlo cuando quieras.`);
      picker.hidden = true;
    });
  });

  const unsentText = $("#unsentText");
  unsentText.value = localStorage.getItem("book-unsent") || "";
  const updateCount = () => $("#charCount").textContent = `${unsentText.value.length} / 500`;
  unsentText.addEventListener("input", updateCount);
  updateCount();
  $("#saveUnsent").addEventListener("click", () => {
    localStorage.setItem("book-unsent", unsentText.value);
    showToast("El mensaje quedó guardado únicamente en este dispositivo.");
  });

  const savedTraffic = localStorage.getItem("book-traffic");
  if (savedTraffic) selectTraffic(savedTraffic, false);
  $$(".traffic-options button").forEach(button => button.addEventListener("click", () => selectTraffic(button.dataset.level, true)));

  const choiceMessages = {
    invite: "Acercarte puede darle una salida sencilla sin obligarlo a explicar cómo se siente. Incluso si dice que no, habrá recibido una señal de inclusión.",
    adult: "Buscar apoyo es útil cuando existe una preocupación mayor. Conviene evitar hablar sobre la persona como si no estuviera presente.",
    wait: "Observar puede ayudarte a entender la situación, pero el silencio también puede prolongar la sensación de aislamiento. Un saludo breve ya modifica el momento."
  };
  $$("#choiceOptions button").forEach(button => {
    button.addEventListener("click", () => {
      const result = $("#choiceResult");
      result.textContent = choiceMessages[button.dataset.choice];
      result.hidden = false;
      $$("#choiceOptions button").forEach(item => item.disabled = true);
    });
  });
}

function selectTraffic(level, announce) {
  const messages = {
    red: "Reconocer que necesitas hablar es una acción importante. Busca a un adulto de confianza y empieza por una sola frase.",
    yellow: "Estás aprendiendo. Puedes identificar una tarea específica en la que necesites acompañamiento.",
    green: "Reconoce tu avance. Poder hacer algo solo no significa que debas dejar de pedir ayuda cuando la necesites."
  };
  $$(".traffic-options button").forEach(button => button.classList.toggle("selected", button.dataset.level === level));
  $("#trafficFeedback").textContent = messages[level];
  localStorage.setItem("book-traffic", level);
  if (announce) showToast("Tu semáforo de hoy quedó registrado en este dispositivo.");
}

function setupNavigation() {
  const button = $("#menuButton");
  const nav = $("#mobileNav");
  button.addEventListener("click", () => {
    const open = button.getAttribute("aria-expanded") === "true";
    button.setAttribute("aria-expanded", String(!open));
    nav.hidden = open;
  });
  $$("#mobileNav a").forEach(link => link.addEventListener("click", () => {
    nav.hidden = true;
    button.setAttribute("aria-expanded", "false");
  }));
}

function setupReader() {
  $("#startReading").addEventListener("click", () => openChapter(state.completed.size < chapters.length ? state.completed.size : 0));
  $("#readerClose").addEventListener("click", () => {
    stopSpeech();
    readerDialog.close();
  });
  $("#readerPrev").addEventListener("click", () => openChapter(state.currentChapter - 1));
  $("#readerNext").addEventListener("click", () => {
    markCompleted(state.currentChapter);
    if (state.currentChapter === chapters.length - 1) {
      readerDialog.close();
      showToast("Terminaste el recorrido. La carta también queda contigo.");
      return;
    }
    openChapter(state.currentChapter + 1);
  });
  $("#readerSpeak").addEventListener("click", event => {
    if (state.speech) stopSpeech();
    else speak(getChapterSpeech(), event.currentTarget);
  });
  $("#readerFont").addEventListener("click", () => {
    readerContent.classList.toggle("large-type");
    showToast(readerContent.classList.contains("large-type") ? "Texto ampliado." : "Tamaño de texto normal.");
  });
  readerDialog.addEventListener("click", event => {
    if (event.target === readerDialog) {
      stopSpeech();
      readerDialog.close();
    }
  });
}

function setupAudio() {
  const introButton = $("#playIntro");
  introButton.dataset.original = "▶ Escuchar introducción";
  introButton.addEventListener("click", () => {
    if (state.speech) {
      stopSpeech();
      introButton.innerHTML = "<span aria-hidden='true'>▶</span> Escuchar introducción";
      return;
    }
    speak("El primer timbre. Lo que dije, lo que pensé y lo que nunca conté sobre mi ingreso a secundaria. Esta historia comienza el último día de primaria y acompaña a un adolescente mientras aprende a reconocer sus emociones, pedir ayuda y encontrar su lugar.", introButton);
  });

  const dailyButton = $("#playDailyVoice");
  dailyButton.dataset.original = "Escuchar esta frase →";
  dailyButton.addEventListener("click", () => {
    if (state.speech) stopSpeech();
    else speak("No tenía miedo del colegio. Tenía miedo de no encontrar un lugar dentro de él.", dailyButton);
  });

  $("#soundToggle").addEventListener("click", event => {
    state.audioEnabled = !state.audioEnabled;
    event.currentTarget.setAttribute("aria-pressed", String(state.audioEnabled));
    event.currentTarget.setAttribute("aria-label", state.audioEnabled ? "Desactivar sonidos ambientales" : "Activar sonidos ambientales");
    if (state.audioEnabled) {
      playBell();
      showToast("Sonido ambiental activado. Solo sonará cuando interactúes con la experiencia.");
    } else {
      showToast("Sonido ambiental desactivado.");
    }
  });
}

function setupDialogsAndPrint() {
  const familyDialog = $("#familyDialog");
  $("#familyGuide").addEventListener("click", () => familyDialog.showModal());
  $$('[data-close-dialog]').forEach(button => button.addEventListener("click", () => $("#" + button.dataset.closeDialog).close()));
  $$(".conversation-card").forEach(button => button.addEventListener("click", () => {
    speak(button.dataset.phrase);
    showToast("Escucha cómo suena la pregunta antes de usarla.");
  }));
  $("#printBook").addEventListener("click", () => window.print());
}

function setupAmbientInteractions() {
  document.addEventListener("click", event => {
    if (!state.audioEnabled) return;
    if (event.target.closest(".chapter-card") || event.target.closest("#startReading")) playBell();
  });
}

function registerServiceWorker() {
  if ("serviceWorker" in navigator && location.protocol.startsWith("http")) {
    window.addEventListener("load", () => navigator.serviceWorker.register("./sw.js").catch(() => {}));
  }
}

